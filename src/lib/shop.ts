/**
 * 店の情報。管理画面の「お店の設定」(/admin/settings)で書き換え、DB の setting に持つ。
 * ここにあるのは形と、まだ何も設定していないときの見本の値だけ(個人の情報は入れない)。
 */
export interface Shop {
  /** 店の名前。ページのタイトルとメールの件名に出る */
  name: string;
  /** トップの見出しの下に出す一言 */
  tagline: string;
  /** 問い合わせ先。特定商取引法の表記・メールの末尾にも出る。空なら出さない */
  email: string;
  /** 運営者の名前。空なら出さない */
  owner: string;
  /** 運営者のサイトや SNS。足元とお店についてに並べる */
  links: { label: string; href: string }[];
  /** 「お店について」の本文(Tiptap の HTML。保存時に sanitize 済み) */
  aboutHtml: string;
  /** 特定商取引法に基づく表記。行の見出しは TOKUSHOHO_ROWS */
  tokushoho: Record<TokushohoKey, string>;
}

